#[test]
fn the_same_commit_from_the_other_repo_or_another_reference_is_another_source() {
    let other_repo = PASS.replacen(
        "git+https://github.com/arnav-hiwarkar/craft-libs-plugin-beta?rev=7ac46cf4574d0d355ffe0c40d9a929b82883232b#",
        "git+https://github.com/storytold/craft-libs?rev=7ac46cf4574d0d355ffe0c40d9a929b82883232b#",
        1,
    );
    assert_eq!(
        check(&other_repo, &Policy::default()),
        Ok(vec![Finding::Stray { package: "craft-atomic".into(), source: source(Repo::Upstream, FORK_7AC), main: source(Repo::Fork, FORK_7AC) }])
    );
    let branch = PASS.replacen("?rev=7ac46cf4574d0d355ffe0c40d9a929b82883232b#", "?branch=platform#", 1);
    let on_branch = Source { repo: Repo::Fork, reference: "branch=platform".into(), commit: Commit::parse(FORK_7AC).unwrap() };
    assert_eq!(
        check(&branch, &Policy::default()),
        Ok(vec![Finding::Stray { package: "craft-atomic".into(), source: on_branch, main: source(Repo::Fork, FORK_7AC) }])
    );
}

#[test]
fn spellings_of_one_repo_url_are_one_source() {
    let spelled = PASS
        .replacen("https://github.com/arnav-hiwarkar/craft-libs-plugin-beta?", "https://github.com/Arnav-Hiwarkar/craft-libs-plugin-beta.git?", 1)
        .replacen("https://github.com/arnav-hiwarkar/craft-libs-plugin-beta?", "ssh://git@github.com/arnav-hiwarkar/craft-libs-plugin-beta/?", 1);
    assert_ne!(spelled, PASS);
    assert_eq!(check(&spelled, &Policy::default()), Ok(vec![]));
}

#[test]
fn a_named_exception_is_honoured_and_an_unused_one_is_reported() {
    let ui = Finding::Stray { package: "craft-ui".into(), source: source(Repo::Upstream, UP_5A7A), main: source(Repo::Fork, FORK_6E4) };
    assert_eq!(check(EFFECTCRAFT_UI, &Policy::default()), Ok(vec![ui]));
    assert_eq!(check(EFFECTCRAFT_UI, &ui_exception()), Ok(vec![]));
    assert_eq!(
        check(PASS, &ui_exception()),
        Ok(vec![Finding::UnusedException { package: "craft-ui".into(), reason: "EffectCraft keeps craft-ui 5a7a63a until EC-UI-PORT".into() }])
    );
    let on_main = Policy::default().except("craft-psd", "kept for a test").unwrap();
    assert_eq!(check(PASS, &on_main), Ok(vec![Finding::UnusedException { package: "craft-psd".into(), reason: "kept for a test".into() }]));
}

