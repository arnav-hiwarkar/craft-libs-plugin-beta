#[test]
fn an_even_split_has_no_framework_source() {
    let split = STRAY.replace(
        "name = \"craft-color\"\nversion = \"0.1.0\"\nsource = \"git+https://github.com/storytold/craft-libs?rev=bafb4522899d9f814a07dad636cdefcbf705dead#bafb4522899d9f814a07dad636cdefcbf705dead\"",
        "name = \"craft-color\"\nversion = \"0.1.0\"\nsource = \"git+https://github.com/storytold/craft-libs?rev=219c1d0b14177af6f291395d6587f61a5e09043a#219c1d0b14177af6f291395d6587f61a5e09043a\"",
    );
    assert_ne!(split, STRAY);
    let policy = Policy::default().except("craft-psd", "kept for a test").unwrap();
    assert_eq!(check(&split, &policy), Ok(vec![Finding::Tied(vec![source(Repo::Upstream, UP_219C), source(Repo::Upstream, UP_BAFB)])]));
    assert_eq!(
        check(&split, &Policy::default()),
        Ok(vec![Finding::Stray {
            package: "craft-automation".into(),
            source: source(Repo::Upstream, UP_BAFB),
            main: source(Repo::Upstream, UP_219C)
        }])
    );
}

#[test]
fn an_empty_lock_fails() {
    assert_eq!(check("", &Policy::default()), Err(Error::Empty));
    assert_eq!(check("# This file is automatically @generated by Cargo.\nversion = 4\n", &Policy::default()), Err(Error::Empty));
}

#[test]
fn a_lock_without_craft_libs_fails() {
    assert_eq!(check(NO_CRAFT_LIBS, &Policy::default()), Err(Error::NoFramework));
    let only_ui = EFFECTCRAFT_UI.replace("arnav-hiwarkar/craft-libs-plugin-beta", "arnav-hiwarkar/other-plugin-beta");
    assert_eq!(check(&only_ui, &Policy::default()), Ok(vec![]));
    assert_eq!(check(&only_ui, &ui_exception()), Err(Error::NoFramework));
}

#[test]
fn a_craft_libs_source_needs_a_full_commit() {
    let short = PASS.replacen("#7ac46cf4574d0d355ffe0c40d9a929b82883232b\"", "#7ac46cf\"", 1);
    assert_eq!(
        check(&short, &Policy::default()),
        Err(Error::Commit {
            package: "craft-atomic".into(),
            source: "https://github.com/arnav-hiwarkar/craft-libs-plugin-beta?rev=7ac46cf4574d0d355ffe0c40d9a929b82883232b#7ac46cf".into()
        })
    );
    let other_short = NO_CRAFT_LIBS.replacen("#e9711ca9b69772f875ae0d1cef1977ff8c16234d\"", "\"", 1);
    assert_eq!(check(&other_short, &Policy::default()), Err(Error::NoFramework));
}

#[test]
fn text_that_is_not_a_lock_is_an_error() {
    assert!(matches!(check("[[package]\nname = 1", &Policy::default()), Err(Error::Parse(_))));
    assert!(matches!(check("package = \"craft-atomic\"", &Policy::default()), Err(Error::Parse(_))));
    assert!(matches!(check("[[package]]\nsource = \"git+https://github.com/storytold/craft-libs\"", &Policy::default()), Err(Error::Parse(_))));
}

#[test]
fn a_lock_of_exactly_the_limit_is_read_and_one_byte_more_is_refused() {
    let at_limit = "\n".repeat(MAX_LOCK_BYTES);
    assert_eq!(check(&at_limit, &Policy::default()), Err(Error::Empty));
    let over = "\n".repeat(MAX_LOCK_BYTES + 1);
    assert_eq!(check(&over, &Policy::default()), Err(Error::TooLarge(16_777_217)));
}

#[test]
fn an_exception_needs_a_package_name_and_a_one_line_reason() {
    assert_eq!(Policy::default().except("craft-ui", ""), Err(Error::Reason("craft-ui".into())));
    assert_eq!(Policy::default().except("craft-ui", "  "), Err(Error::Reason("craft-ui".into())));
    assert_eq!(Policy::default().except("craft-ui", "two\nlines"), Err(Error::Reason("craft-ui".into())));
    assert_eq!(Policy::default().except("", "a reason"), Err(Error::ExceptionName("".into())));
    assert_eq!(Policy::default().except("craft ui", "a reason"), Err(Error::ExceptionName("craft ui".into())));
    assert_eq!(ui_exception().except("craft-ui", "again"), Err(Error::DuplicateException("craft-ui".into())));
}

